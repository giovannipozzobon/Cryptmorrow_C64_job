"""Verify a step of the chain of the book (steps 01-06) in a private VICE.

Usage: python tests/verify_step.py --step N [--vice PATH] [--settle S]

The step is chain/NN-name/, generated by tools/make_chain.py and
assembled (make_chain.py --assemble, or tools/run-game.ps1 -Mode Build
in the step's folder). Steps 07 and 08 are the complete program and
have tests/verify_game.py (--step 7, --step 8).

1. Data: every data block the step has is its generated file (the
   music: the assembled bytes), in the PRG and at its address in
   memory; the code ends below the data.
2. The start: the PRG is written into memory again, as LOAD leaves it,
   and run from `entry`: the start room is drawn with the display off,
   timed at every cell row, then shown; the VIC set up for the
   multicolour bitmap (bank, addresses, mode); bitmap, screen RAM,
   Color RAM, walkability map and torch list equal to the reference
   renderer (tests/reference.py); step 06 with the sound interrupt
   running from the start.
3. The route of the step, tests/routes/step_NN.py (planned offline by
   tools/plan_route.py --step N tools/route_step_NN.py), replayed with
   the joystick and compared every frame with tests/step_model.py: the
   explorer and sprite 0 (from 02), room and game state (from 03), the
   objects, doors and the end of a game (from 04), the combat state and
   sprites 1-4 (from 05), the sound state and the 25 shadow SID
   registers, with the rules of silence (06). New games begin by
   loading and starting the program again (steps 04-06: a game that is
   over stands still); in step 06 the test may put another mode in
   audio_mode before start_audio, as if START_MODE said so. Screens are
   compared when drawn or changed, changes of room timed, the work of
   every frame measured, the torches checked every 8 frames and the
   bitmap outside them every 64.
4. From step 04: HUD values written by the test, rewritten by
   hud_update as the reference.
5. What the step must show (STEP_CHECKS) and native screenshots.
The report goes to chain/evidence/NN-name/step-test.json with the
screenshots.
"""
