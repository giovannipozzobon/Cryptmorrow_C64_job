MUSIC_BUDGET = 2500             # cycles of the sound interrupt, at most
ALIGN = 32
MODES = ("MUSIC", "FX", "SILENT")
SIDES = {-4: "north", 4: "south", -1: "west", 1: "east"}
HERO_COLOUR = 5
HUD_TEST = (3, 2, 1, 12345)
# The VIC as main.asm sets it up: bitmap on, 25 rows, Y scroll 3;
# multicolour, 40 columns, X scroll 0; screen $4400, bitmap $6000;
# bank $4000-$7fff ($dd00 bits = 2).
VIDEO = {"$d011": 0x3B, "$d016": 0x18, "$d018": 0x18, "bank": 2}
PROBES = {"MUSIC": 600, "FX": 4000, "SILENT": 500,
          "MUSIC, end of a game": 400}
# Data blocks: address label, generated file, first step (data.asm).
BLOCKS = [("SPRITE_DATA", "hero.sprites", 2),
          ("OBJECT_SPRITES", "objects.sprites", 4),
          ("COMBAT_SPRITES", "combat.sprites", 5),
          ("TILE_BITMAP", "tiles.bitmap", 1),
          ("TILE_ATTR", "tiles.attr", 1),
          ("FLAMES", "flames.bin", 1), ("FONT", "font.bin", 1),
          ("DOOR_TILES", "doors.bin", 4), ("ROOM_DATA", "rooms.bin", 1),
          ("ZONE_COLOURS", "zones.color", 1)]
# The game state variables of world.asm, with their sizes.
STATE = [("room_slot", 1), ("energy", 1), ("key_set", 1), ("seals", 1),
         ("doors_open", 1), ("taken", 4), ("score", 3), ("hud_dirty", 1),
         ("game_ended", 1)]
ENDED = {None: 0, "lost": C.ENDED_LOST, "won": C.ENDED_WON}


def step_root(step):
    found = sorted((PROJECT / "chain").glob(f"{step:02d}-*"))
    require(len(found) == 1, f"Step {step} not found in chain/")
    return found[0]


def load_script(step, path=None):
    path = path or PROJECT / "tests/routes" / f"step_{step:02d}.py"
    spec = importlib.util.spec_from_file_location(path.stem, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.SCRIPT


def bcd(number):
    text = f"{number:06d}"
    return bytes(int(text[i]) << 4 | int(text[i + 1]) for i in (0, 2, 4))


def verify(args):
    step = args.step
    require(1 <= step <= 6, "verify_step.py is for steps 1-6")
    root = args.root.resolve() if args.root else step_root(step)
    reference.GENERATED = root / "game/assets/generated"   # its own
    for statement in args.set:          # a variant changes the model
        exec(statement, {"step_model": S, "hero_model": H,
                         "world_model": W, "combat_model": C,
                         "reference": reference})
    prg = root / "game/build/cryptmorrow.prg"
    labels = load_labels(root / "game/build/cryptmorrow.lbl")
    has = {name: step >= first for name, first in (
        ("hero", S.FIRST_HERO), ("exits", S.FIRST_EXITS),
        ("objects", S.FIRST_OBJECTS), ("combat", S.FIRST_COMBAT),
        ("sound", S.FIRST_SOUND))}
    evidence_rel = args.evidence or f"chain/evidence/{root.name}"
    evidence = PROJECT / evidence_rel
    evidence.mkdir(parents=True, exist_ok=True)
    script = load_script(step, args.script)
    report = {"result": "FAIL", "step": root.name,
              "prg_sha256": hashlib.sha256(prg.read_bytes()).hexdigest(),
              "screenshots": [], "segments": [], "transitions": [],
              "starts": [], "events": []}
    vice = Vice(args.vice, prg, evidence / "step-test-vice.log",
                evidence_rel)
    try:
        monitor = vice.connect(args.settle)
        note(f"{root.name}: monitor connected")

        def word(address):
            return struct.unpack("<H", monitor.memory(address, 2))[0]

        # --- 1. the data at their addresses ------------------------
        image = prg.read_bytes()
        load, body = image[0] | image[1] << 8, image[2:]
        checked = []
        for name, file, first in BLOCKS:
            present = name in labels and step >= first
            if not present:
                continue
            address, data = labels[name], reference.load(file)
            require(body[address - load:address - load + len(data)] ==
                    data, f"PRG: {file} not at {name}")
            require(monitor.memory(address, len(data)) == data,
                    f"Memory: {file} not at {name} ({address:#06x})")
            checked.append(file)
        if has["sound"]:
            size = load + len(body) - labels["MUSIC_DATA"]
            require(monitor.memory(labels["MUSIC_DATA"], size) ==
                    body[labels["MUSIC_DATA"] - load:],
                    "Memory: the music data not as assembled")
            checked.append(f"music ({size} bytes)")
        lowest = min(labels[n] for n, _, f in BLOCKS
                     if n in labels and step >= f)
        require(labels["code_end"] <= lowest,
                f"code_end {labels['code_end']:#06x} runs into the data")
        report["data"] = {
            "blocks": checked, "code_end": f"${labels['code_end']:04x}",
            "lowest_data": f"${lowest:04x}",
            "prg_bytes": len(image),
            "checks": "each block equal to its generated file in the "
                      "PRG and in memory at its address; the code ends "
                      "below the data"}

        # --- 2. starts: the program from entry ---------------------
        hud_frame = monitor.memory(labels["hud_frame"], 256) \
            if "hud_frame" in labels else None
        texts = [monitor.memory(labels[name], 32) if name in labels
                 else None for name in ("over_text", "won_text")]
        start_room = labels["START_ROOM"]
        flames = reference.load("flames.bin")
        zp = labels.get("joy_state", 2)
        frames_at = labels["frame_count"]
        state_names = [(n, s) for n, s in STATE if n in labels]
        state_from = min(labels[n] for n, _ in state_names)
        state_size = max(labels[n] + s for n, s in state_names) - \
            state_from
        if has["combat"]:
            combat_at = labels["slash_timer"]
            combat_size = labels["enemy_slot"] - combat_at
            require(combat_size == 5 + 10 * C.MAX_ENEMIES,
                    f"Combat state block of {combat_size} bytes")
        if has["sound"]:
            audio_at = labels["audio_mode"]
            audio_size = labels["sid_shadow"] + 25 - audio_at
            require(audio_size == 36, f"Sound state block of {audio_size}")
            memory = bytearray(65536)
            memory[0x0801:0x4000] = monitor.memory(0x0801, 0x4000 - 0x0801)
            memory[0xC000:0xD000] = monitor.memory(0xC000, 0x1000)
            pieces = json.loads((reference.GENERATED / "assets.json")
                                .read_text())["music"]["songs"]
            piece_frames = {labels["SONG_WON"]: pieces["won"]["frames"],
                            labels["SONG_LOST"]: pieces["lost"]["frames"]}

        def compare(wanted, what, torches=True):
            """The whole screen against a reference (as verify_game)."""
            count = monitor.memory(labels["torch_count"], 1)[0]
            low = monitor.memory(labels["torch_lo"], 6)
            high = monitor.memory(labels["torch_hi"], 6)
            listed = [low[i] | high[i] << 8 for i in range(count)]
            require(listed == wanted.torches,
                    f"{what}: torch list {listed} != {wanted.torches}")
            offsets = {a - 0x6000 + i for a in listed for i in range(8)}
            bitmap = monitor.memory(0x6000, 8000)
            for i in range(8000):
                if i not in offsets and bitmap[i] != wanted.bitmap[i]:
                    raise RuntimeError(f"{what}: bitmap differs from the "
                                       f"reference at cell {i // 8}")
            if torches:
                phase = monitor.memory(labels["torch_phase"], 1)[0]
                for address in listed:
                    require(monitor.memory(address, 8) ==
                            flames[phase * 8:phase * 8 + 8],
                            f"{what}: flame at {address:#06x}")
            for name, address, table in (
                    ("screen RAM", 0x4400, wanted.screen),
                    ("walkability map", labels["SOLID_MAP"], wanted.solid)):
                actual = monitor.memory(address, 1000)
                if actual != bytes(table):
                    first = next(i for i in range(1000)
                                 if actual[i] != table[i])
                    raise RuntimeError(f"{what}: {name} differs at {first}")
            colour = bytes(b & 15 for b in monitor.memory(0xD800, 1000))
            if colour != bytes(wanted.color):
                first = next(i for i in range(1000)
                             if colour[i] != wanted.color[i])
                raise RuntimeError(f"{what}: Color RAM differs at {first}")

        def draw_timing(stops_before=()):
            """From a stop before enter_room to room_shown: the display
            blanked, 20 cell rows timed, the display on again."""
            require(monitor.run_until_stop() == labels["room_blank"],
                    "No drawing of a room started")
            require(monitor.memory(0xD011, 1)[0] & 0x10 == 0,
                    "Display not blanked before drawing")
            previous, cycles, rows = monitor.raster_time(), 0, 0
            while True:
                stop = monitor.run_until_stop()
                now = monitor.raster_time()
                cycles += (now - previous) % PAL_FRAME_CYCLES
                previous = now
                if stop == labels["room_drawn"]:
                    break
                require(stop == labels["next_cell_row"],
                        f"Unexpected stop at {stop:#06x}")
                rows += 1
            require(rows == 20, f"{rows} cell rows drawn, not 20")
            require(monitor.memory(0xD011, 1)[0] & 0x10 == 0,
                    "Display switched on during the drawing")
            require(monitor.run_until_stop() == labels["room_shown"],
                    "enter_room did not reach room_shown")
            require(monitor.memory(0xD011, 1)[0] & 0x7F == 0x3B,
                    "Display not switched on again")
            return cycles

        room_marks = ("room_blank", "next_cell_row", "room_drawn",
                      "room_shown")

        def start_program(mode):
            """The program from entry, as loaded: returns the model of
            the new game and, in step 06, the sound model."""
            marks = [monitor.checkpoint(labels[name]) for name in
                     room_marks]
            audio_point = monitor.checkpoint(labels["start_audio"]) \
                if has["sound"] else None
            monitor.poke(load, body)        # the PRG as LOAD leaves it
            monitor.set_pc(labels["entry"])
            audio_model, irq_start = None, None
            if has["sound"]:
                require(monitor.run_until_stop() == labels["start_audio"],
                        "entry did not call start_audio")
                if mode is not None:             # as if START_MODE
                    monitor.poke(labels["audio_mode"], bytes([mode]))
                else:
                    mode = labels["START_MODE"]
                require(monitor.memory(labels["audio_mode"], 1)[0] == mode,
                        "audio_mode is not the mode of the start")
                irq_start = word(labels["irq_frames"])
                audio_model = AudioModel(memory, labels, mode)
                audio_model.irq_frames = irq_start
                monitor.delete_checkpoint(audio_point)
            cycles = draw_timing()
            for number in marks:
                monitor.delete_checkpoint(number)
            monitor.run_to(labels["main_loop"])
            require(word(frames_at) == 0, "frame_count not 0 at the start")
            vic = monitor.memory(0xD011, 8)     # $d011-$d018
            bank = monitor.memory(0xDD00, 1)[0] & 3
            video = {"$d011": vic[0] & 0x7F, "$d016": vic[5] & 0x1F,
                     "$d018": vic[7] & 0xFE, "bank": bank}   # bit 0: 1
            require(video == VIDEO, f"VIC set up as {video}, not {VIDEO}")
            require(monitor.read_registers()["01"] & 7 == 6,
                    "$01 must be $36: RAM visible at $a000")
            model = S.StepGame(step, hud_frame, start_room, texts,
                               labels.get("HERO_START_X"),
                               labels.get("HERO_START_Y"), frame=0,
                               mode=mode if has["sound"] else MODE_MUSIC)
            blank = None
            if has["sound"]:
                blank = (word(labels["irq_frames"]) - irq_start) & 0xFFFF
                for _ in range(blank):
                    audio_model.irq()
            compare(model.world.screen(), "Start room")
            start = {"draw_room_cycles": cycles,
                     "torches": len(model.world.screen().torches),
                     "mode": MODES[mode] if has["sound"] else None,
                     "interrupts_while_starting": blank}
            report["starts"].append(start)
            note(f"start: draw_room {cycles} cycles")
            return model, audio_model

        # --- per-frame checks --------------------------------------
        def hero_state():
            data = monitor.memory(zp, 8)
            vic = monitor.memory(0xD000, 0x2F)
            pointers = monitor.memory(0x47F8, 8)
            return {"x": data[1] | data[2] << 8, "y": data[3],
                    "dir": data[4], "moving": data[5], "frame": data[6],
                    "timer": data[7], "pointer": pointers[0],
                    "pointers": pointers, "vic": vic,
                    "vic_x": vic[0] + 256 * (vic[0x10] & 1),
                    "vic_y": vic[1]}

        def check_hero():
            state = hero_state()
            model = game.hero
            wanted = {"x": model.x, "y": model.y, "dir": model.dir,
                      "moving": model.moving, "frame": model.frame,
                      "timer": model.timer, "pointer": model.pointer}
            actual = {k: state[k] for k in wanted}
            require(actual == wanted, f"Frame {frame}: C64 {actual} != "
                                      f"model {wanted}")
            require(state["vic_x"] == model.x + 24 and
                    state["vic_y"] == model.y + 50,
                    f"Frame {frame}: sprite registers do not follow")
            return state

        def check_state():
            data = monitor.memory(state_from, state_size)

            def value(name, size=1):
                at = labels[name] - state_from
                return data[at:at + size]
            world = game.world
            actual, wanted = {}, {}
            actual["room"], wanted["room"] = value("room_slot")[0], \
                world.slot
            if "energy" in labels:
                actual.update(energy=value("energy")[0],
                              key_set=value("key_set")[0],
                              seals=value("seals")[0])
                digits = value("score", 3).hex()
                require(digits.isdigit(), f"Score {digits} is not BCD")
                actual["score"] = int(digits)
                wanted.update(energy=world.energy, key_set=world.key_set,
                              seals=world.seals, score=world.score)
            if "doors_open" in labels:
                taken = value("taken", 4)
                actual.update(doors_open=value("doors_open")[0],
                              taken={n for n in range(32)
                                     if taken[n // 8] >> (n % 8) & 1},
                              ended=value("game_ended")[0])
                wanted.update(doors_open=world.doors_open,
                              taken=world.taken, ended=ENDED[world.ended])
            require(actual == wanted, f"Frame {frame}: game state "
                                      f"{actual} != model {wanted}")

        def check_combat():
            data = monitor.memory(combat_at, combat_size)
            n = C.MAX_ENEMIES
            enemies = []
            for slot in range(n):
                kind, low, high, y, way, hp, flash, dust, hit, fast = (
                    data[5 + i * n + slot] for i in range(10))
                enemies.append((kind, low | high << 8, y, way, hp, flash,
                                dust, hit, fast))
            actual = (*data[:5], enemies)
            fight = game.combat
            wanted = (fight.slash, fight.blade_dir, fight.fire_held,
                      fight.safe, fight.ended,
                      [(kind, x & 0xFFFF, y & 255, *rest) for
                       kind, x, y, *rest in (e.state()
                                             for e in fight.enemies)])
            require(actual == wanted, f"Frame {frame}: combat state "
                                      f"{actual} != model {wanted}")

        seen = {"pointers": set(), "blade": set(), "enemy_pointers": set(),
                "hidden": 0, "flash": 0, "blocked_dirs": set(),
                "blocks": set(), "door_blocks": set(), "horizontal": 0,
                "up_wins": 0, "potion_refused": 0, "still": 0,
                "clamp": 0}

        def check_sprites(state):
            vic, pointers, on = state["vic"], state["pointers"], \
                state["vic"][0x15]
            shown, blade, enemies, objects = expected_sprites
            require(bool(on & 1) == shown, f"Frame {frame}: explorer "
                    f"{'shown' if on & 1 else 'hidden'}")
            require(vic[0x27] & 15 == HERO_COLOUR,
                    f"Frame {frame}: explorer colour {vic[0x27] & 15}")
            wanted = [(1, blade)]
            wanted += [(2 + n, e) for n, e in enumerate(enemies)]
            wanted += [(5 + n, o) for n, o in enumerate(objects)]
            for sprite, model_sprite in wanted:
                visible = bool(on >> sprite & 1)
                require(visible == (model_sprite is not None),
                        f"Frame {frame}: sprite {sprite} "
                        f"{'on' if visible else 'off'}, model "
                        f"{model_sprite}")
                if model_sprite is None:
                    continue
                actual = (pointers[sprite], vic[0x27 + sprite] & 15,
                          vic[2 * sprite] + 256 * (vic[0x10] >> sprite & 1),
                          vic[2 * sprite + 1])
                require(actual == model_sprite, f"Frame {frame}: sprite "
                        f"{sprite} {actual} != model {model_sprite}")
            require(on & 0x80 == 0, f"Frame {frame}: sprite 7 switched on")
            multicolour = 1 | (0x60 if has["objects"] else 0) | \
                (0x1C if has["combat"] else 0)
            require(vic[0x1C] & 0x7F == multicolour,
                    f"Frame {frame}: multicolour bits {vic[0x1C]:08b}")
            seen["hidden"] += not shown
            if blade:
                seen["blade"].add(blade[0])
            for enemy in enemies:
                if enemy:
                    seen["enemy_pointers"].add(enemy[0])
                    seen["flash"] += enemy[1] == C.FLASH_COLOUR

        audio_seen = {"frames": {m: 0 for m in MODES}}
        quiet = {"SILENT: volume 0": 0,
                 "SOUND FX: voices 2 and 3 never gated": 0,
                 "SOUND FX, no effect: voice 1 gate off": 0,
                 "MUSIC, piece of VICTORY over: every gate off": 0,
                 "MUSIC, piece of GAME OVER over: every gate off": 0}

        def check_audio():
            data = monitor.memory(audio_at, audio_size)
            actual = {"mode": data[0], "fx_next": data[3],
                      "fx_pos": data[4], "fx_prio": data[5],
                      "song": data[7], "music_tick": data[8],
                      "music_frames": data[9] | data[10] << 8,
                      "shadow": list(data[11:36])}
            require((data[1] | data[2] << 8) == audio.irq_frames,
                    f"Frame {frame}: interrupt count "
                    f"{data[1] | data[2] << 8}, model {audio.irq_frames}")
            wanted = audio.state()
            if actual != wanted:
                diff = {k: (actual[k], wanted[k]) for k in actual
                        if actual[k] != wanted[k]}
                raise RuntimeError(f"Frame {frame}: sound state differs "
                                   f"from the model (C64, model): {diff}")
            audio_seen["frames"][MODES[audio.mode]] += 1
            shadow = actual["shadow"]
            gates = [shadow[4] & 1, shadow[11] & 1, shadow[18] & 1]
            if actual["mode"] == MODE_SILENT:
                require(shadow[24] & 15 == 0, f"Frame {frame}: SILENT "
                        f"with volume {shadow[24] & 15}")
                quiet["SILENT: volume 0"] += 1
            elif actual["mode"] == MODE_FX:
                require(not gates[1] and not gates[2], f"Frame {frame}: "
                        f"a note left on voice 2 or 3, gates {gates}")
                quiet["SOUND FX: voices 2 and 3 never gated"] += 1
                if not actual["fx_pos"] and not actual["fx_next"]:
                    require(not gates[0], f"Frame {frame}: voice 1 still "
                            f"gated with no effect playing")
                    quiet["SOUND FX, no effect: voice 1 gate off"] += 1
            elif actual["song"] in piece_frames and \
                    actual["music_frames"] >= piece_frames[actual["song"]]:
                require(not any(gates), f"Frame {frame}: gates {gates} "
                        f"after the piece of the end is over")
                won_piece = actual["song"] == labels["SONG_WON"]
                quiet[f"MUSIC, piece of "
                      f"{'VICTORY' if won_piece else 'GAME OVER'} over: "
                      f"every gate off"] += 1

        def check_frame(state=None):
            require(word(frames_at) == frame and game.frame == frame,
                    f"Frame count off at {frame}")
            if has["hero"]:
                state = check_hero()
                seen["pointers"].add(state["pointer"])
                check_sprites(state)
            else:
                require(monitor.memory(0xD015, 1)[0] == 0,
                        f"Frame {frame}: a sprite switched on")
            check_state()
            if has["combat"]:
                check_combat()
            if has["sound"]:
                check_audio()

        def check_hud():
            wanted = game.world.screen()
            require(monitor.memory(0x6000, 3 * 320) ==
                    bytes(wanted.bitmap[:3 * 320]) and
                    monitor.memory(0x4400, 3 * 40) ==
                    bytes(wanted.screen[:3 * 40]),
                    f"Frame {frame}: HUD differs from the reference for "
                    f"{game.world.hud_values()}")

        probe = {"on": False, "points": [], "costs": {k: [] for k in
                                                      PROBES}}

        def probe_kind():
            if not has["sound"]:
                return None
            if audio.mode == MODE_FX:
                kind = "FX"
            elif audio.mode == MODE_SILENT:
                kind = "SILENT"
            elif game.world.ended and audio.player.song != \
                    labels["SONG_THEME"]:
                kind = "MUSIC, end of a game"
            else:
                kind = "MUSIC"
            return kind if len(probe["costs"][kind]) < PROBES[kind] \
                else None

        def set_probe(wanted):
            if wanted == probe["on"]:
                return
            if wanted:
                probe["points"] = [monitor.checkpoint(labels[name])
                                   for name in ("audio_irq", "irq_done")]
            else:
                for number in probe["points"]:
                    monitor.delete_checkpoint(number)
            probe["on"] = wanted

        def advance(target):
            begin = None
            while True:
                stop = monitor.run_until_stop()
                if stop == target:
                    return
                if stop == labels.get("audio_irq"):
                    begin = monitor.raster_time()
                elif stop == labels.get("irq_done") and begin is not None:
                    kind = probe_kind()
                    if kind:
                        probe["costs"][kind].append(
                            (monitor.raster_time() - begin) %
                            PAL_FRAME_CYCLES)
                    begin = None

        def play_sounds(sounds, drawn):
            if ("draw",) not in sounds:
                sounds = list(sounds) + [("draw",)]
            for item in sounds:
                if item == ("draw",):
                    for _ in range(drawn):
                        audio.irq()
                else:
                    audio.request(item)

        def current():
            return game.world.screen()

        totals = {"frames": 0, "near_hits": 0, "started": {},
                  "refused": 0, "replaced": 0, "songs": set()}

        def retire(old_game, old_audio, frames):
            """Adds up what a game showed before the next start."""
            totals["frames"] += frames
            totals["near_hits"] += old_game.combat.near_hits
            if old_audio is not None:
                for number, times in old_audio.started.items():
                    totals["started"][number] = \
                        totals["started"].get(number, 0) + times
                totals["refused"] += old_audio.refused
                totals["replaced"] += old_audio.replaced
                totals["songs"].update(old_audio.songs)

        # --- 3. the route --------------------------------------------
        frame_stop = labels["joy_ready"] if has["hero"] else \
            labels["main_loop"]
        for name in ("main_loop", "joy_ready"):
            if name in labels and (name == "main_loop" or has["hero"]):
                monitor.checkpoint(labels[name])
        game, audio = start_program(None)
        frame = 0
        expected_sprites = game.sprites()
        check_frame()
        costs, blocked_frames, total_steps = [], 0, 0
        visited, openings = {game.world.slot}, set()
        end_states, game_help, restarts = [], [], 0
        last_hud = game.world.hud_values()
        early = 0
        phases = set()
        for joy, count, expectation, shot in script:
            if joy == "restart":
                set_probe(False)
                retire(game, audio, frame)
                game, audio = start_program(None if count < 0 else count)
                frame, early = 0, 0
                restarts += 1
                game_help = []
                expected_sprites = game.sprites()
                last_hud = game.world.hud_values()
                visited.add(game.world.slot)
                check_frame()
                report["events"].append({"game": restarts + 1,
                                         "frame": frame, "event":
                                         "program loaded and started "
                                         "again"})
                continue
            if joy in ("energy", "seals", "enemy", "slow"):
                game_help.append(joy)
            if joy == "slow":
                monitor.poke(labels["en_fast"] + count, b"\x00")
                game.combat.enemies[count].fast = 0
                report["events"].append({"game": restarts + 1,
                                         "frame": frame, "event":
                                         f"test makes enemy {count} slow"})
                continue
            if joy in ("energy", "seals"):
                monitor.poke(labels[joy], bytes([count]))
                monitor.poke(labels["hud_dirty"], b"\x01")
                setattr(game.world, joy, count)
                report["events"].append({"game": restarts + 1,
                                         "frame": frame, "event":
                                         f"test sets {joy} to {count}"})
                continue
            if joy == "enemy":
                slot, (x, y) = count, expectation
                for name, value in (("en_x_lo", x & 255),
                                    ("en_x_hi", x >> 8), ("en_y", y)):
                    monitor.poke(labels[name] + slot, bytes([value]))
                enemy = game.combat.enemies[slot]
                enemy.x, enemy.y = x, y
                report["events"].append({"game": restarts + 1,
                                         "frame": frame, "event":
                                         f"test moves enemy {slot} to "
                                         f"({x}, {y})"})
                continue
            if joy == "align":
                joy, count = 0, (count - frame) % ALIGN
            hero_now = game.hero
            start = (game.world.slot, hero_now and hero_now.x,
                     hero_now and hero_now.y, game.world.ended)
            enemies_from = [(e.kind, e.x, e.y) for e in
                            game.combat.enemies if e.kind]
            steps0 = hero_now.steps if hero_now else 0
            entered, ended_here = [], False
            for _ in range(count):
                old_slot = game.world.slot
                energy_before = game.world.energy
                steps_before = game.hero.steps if game.hero else 0
                events_before = len(game.world.events)
                ended_before = game.world.ended
                result = game.step(joy)
                drawing = result["room"] is not None
                set_probe(bool(probe_kind()) and not drawing)
                advance(frame_stop)
                if has["sound"]:
                    interrupts = (word(labels["irq_frames"]) -
                                  audio.irq_frames) & 0xFFFF
                    require(interrupts == 1 - early, f"Frame {frame + 1}: "
                            f"{interrupts} interrupts since the last frame")
                    for _ in range(interrupts):
                        audio.irq()
                early = 0
                change = None
                if not drawing:
                    begin = monitor.raster_time()
                    if has["hero"]:
                        monitor.poke(zp, bytes([joy]))
                        advance(labels["main_loop"])
                    end = monitor.raster_time()
                    if has["hero"]:
                        require(end > begin, f"Frame {frame + 1}: the "
                                             f"work ran past the frame")
                        costs.append((end - begin, frame + 1,
                                      game.world.slot, restarts + 1))
                    if has["sound"]:
                        play_sounds(result["sounds"], 0)
                else:
                    marks = [monitor.checkpoint(labels[name]) for name in
                             room_marks]
                    irq_before = word(labels["irq_frames"]) \
                        if has["sound"] else 0
                    monitor.poke(zp, bytes([joy]))
                    draw = draw_timing()
                    for number in marks:
                        monitor.delete_checkpoint(number)
                    blank = ((word(labels["irq_frames"]) - irq_before) &
                             0xFFFF) if has["sound"] else None
                    change = {"from": old_slot, "draw_cycles": draw,
                              "blank_frames": blank}
                    if has["sound"]:
                        play_sounds(result["sounds"], blank)
                    monitor.run_to(labels["main_loop"])
                frame += 1
                model = game.hero
                if result["hurt"] and energy_before < C.DAMAGE:
                    seen["clamp"] += 1          # stopped at zero
                if not ended_before:            # play_frame ran
                    expected_sprites = game.sprites()
                if model is not None and joy & 15:
                    if model.steps == steps_before:
                        blocked_frames += not game.world.ended
                        if not ended_before:
                            seen["blocked_dirs"].add(model.dir)
                            seen["blocks"].add(model.block)
                            if model.block == reference.DOOR_CELL:
                                seen["door_blocks"].add(game.world.slot)
                        else:
                            seen["still"] += 1
                    if joy & (H.JOY_LEFT | H.JOY_RIGHT) and \
                            joy & (H.JOY_UP | H.JOY_DOWN) and \
                            model.dir in (H.DIR_LEFT, H.DIR_RIGHT):
                        seen["horizontal"] += 1
                    if joy & 3 == 3 and model.dir == H.DIR_UP:
                        seen["up_wins"] += 1
                if model is not None and has["objects"] and \
                        game.world.energy >= W.ENERGY_MAX:
                    column = (model.x + W.HIT_X) // 16
                    row = (model.y + W.HIT_Y - 24) // 16
                    seen["potion_refused"] += any(
                        kind == W.KIND_POTION and (c, r) == (column, row)
                        for _, kind, c, r, _ in game.world.objects())
                check_frame()
                if change is not None:
                    compare(current(), f"Room {game.world.slot}")
                    new_slot = game.world.slot
                    zone = game.world.page()[reference.ZONE_AT]
                    require(monitor.memory(labels["colour_zone"], 1)[0]
                            == zone, f"Room {new_slot}: colour_zone is "
                                     f"not zone {zone}")
                    side = SIDES[new_slot - old_slot]
                    openings.add((old_slot, side))
                    visited.add(new_slot)
                    entered.append(new_slot)
                    change.update(to=new_slot, side=side, zone=zone,
                                  frame=frame, entry=[model.x, model.y])
                    report["transitions"].append(change)
                    note(f"room {old_slot} -> {new_slot} ({side}): "
                         f"{change['draw_cycles']} cycles")
                if result["opened"] or result["over"] or result["won"]:
                    compare(current(), f"Room {game.world.slot}")
                if game.world.ended and not ended_before:
                    ended_here = True
                    world = game.world
                    end_states.append({
                        "game": restarts + 1, "how": world.ended,
                        "frame": frame,
                        "room": world.slot,
                        "mode": MODES[game.mode] if has["sound"] else None,
                        "energy": world.energy, "keys": world.keys(),
                        "seals": world.seals, "score": world.score,
                        "doors_open": world.doors_open,
                        "objects_taken": sorted(world.taken),
                        "test_help": sorted(set(game_help)),
                        "joystick_only": not game_help})
                if has["objects"] and not ended_before and \
                        game.world.hud_values() != last_hud:
                    check_hud()
                    last_hud = game.world.hud_values()
                report["events"].extend(
                    {"game": restarts + 1, "frame": frame,
                     "room": game.world.slot, "event": event}
                    for event in game.world.events[events_before:])
                if frame % (1 << S.FLAME_SHIFT) == 0:
                    phase = (frame >> S.FLAME_SHIFT) & 3
                    phases.add(phase)
                    require(monitor.memory(labels["torch_phase"], 1)[0]
                            == phase, f"Torch phase wrong at {frame}")
                    for address in current().torches:
                        require(monitor.memory(address, 8) ==
                                flames[phase * 8:phase * 8 + 8],
                                f"Flame at {address:#06x} not phase "
                                f"{phase}")
                if frame % 64 == 0:
                    wanted_now = current()
                    offsets = {a - 0x6000 + i for a in wanted_now.torches
                               for i in range(8)}
                    bitmap = monitor.memory(0x6000, 8000)
                    require(all(bitmap[i] == wanted_now.bitmap[i]
                                for i in range(8000) if i not in offsets),
                            f"Bitmap changed outside the torches ({frame})")
            hero_now = game.hero
            steps = hero_now.steps - steps0 if hero_now else 0
            total_steps += steps
            note(f"joy={joy:05b} x{count}: {start} -> "
                 f"{game.world.slot}, {steps} steps")
            if expectation == "ending":
                require(ended_here and not entered, f"Segment joy="
                        f"{joy:05b}: expected the end of the game")
            elif expectation == "idle":
                require(not entered and not steps and not ended_here,
                        f"Segment joy={joy:05b} expected idle")
            elif expectation == "still":
                require(not entered and not steps and not ended_here,
                        f"Segment joy={joy:05b} expected still")
            elif isinstance(expectation, int):
                require(entered == [expectation] and not ended_here,
                        f"Segment joy={joy:05b} expected room "
                        f"{expectation}, entered {entered}")
            else:
                require(not entered and not ended_here and
                        not game.world.ended, f"Unexpected change "
                        f"{entered}, ended {game.world.ended}")
                if expectation == "blocked":
                    require(steps == 0, f"Segment joy={joy:05b} expected "
                                        f"blocked, made {steps} steps")
                elif expectation == "moves":
                    require(steps, f"Segment joy={joy:05b} expected moves")
            report["segments"].append({
                "joy": f"{joy:05b}", "frames": count, "from": list(start),
                "to": [game.world.slot, hero_now and hero_now.x,
                       hero_now and hero_now.y, game.world.ended],
                "steps": steps, "expected": expectation,
                "enemies_from": enemies_from,
                "enemies_to": [(e.kind, e.x, e.y) for e in
                               game.combat.enemies if e.kind]})
            if shot:
                set_probe(False)
                capture = vice.screenshot(shot)
                capture.update(frame=frame, room=game.world.slot,
                               ended=game.world.ended)
                monitor.read_registers()
                monitor.run_to(labels["main_loop"])
                idle = word(frames_at) - frame
                require(0 < idle <= 200, f"Odd drift after screenshot "
                                         f"{idle}")
                events_before = len(game.world.events)
                for _ in range(idle):
                    ended_before = game.world.ended
                    result = game.step(0)
                    require(not result["sounds"] and
                            result["room"] is None, "Something happened "
                                                    "while idle")
                    if not ended_before:
                        expected_sprites = game.sprites()
                    if has["sound"]:
                        audio.irq()
                require(len(game.world.events) == events_before,
                        "Something happened while idle")
                if has["sound"]:
                    early = ((word(labels["irq_frames"]) - audio.irq_frames)
                             & 0xFFFF)
                    require(early in (0, 1), f"{early} interrupts early")
                    for _ in range(early):
                        audio.irq()
                frame += idle
                check_frame()
                capture["idle_frames_during_export"] = idle
                report["screenshots"].append(capture)
        set_probe(False)
        retire(game, audio, frame)
        audio_started = totals["started"]
        refused, replaced = totals["refused"], totals["replaced"]
        songs = totals["songs"]
        require(len(report["screenshots"]) == sum(
            1 for s in script if isinstance(s[0], int) and s[3]),
            "A screenshot missing")

        # --- 4. HUD values -------------------------------------------
        if has["objects"]:
            require(not game.world.ended, "The route must end in a game "
                                          "that goes on, for the HUD test")
            points = [monitor.checkpoint(labels[name]) for name in
                      ("hud_update", "hud_ready")]

            def show_hud(values):
                energy, keys, seals, score = values
                monitor.run_to(labels["main_loop"])
                monitor.poke(labels["energy"], bytes([energy]))
                monitor.poke(labels["key_set"], bytes([(1 << keys) - 1]))
                monitor.poke(labels["seals"], bytes([seals]))
                monitor.poke(labels["score"], bcd(score))
                monitor.poke(labels["hud_dirty"], b"\x01")
                monitor.run_to(labels["hud_update"])
                begin = monitor.raster_time()
                monitor.run_to(labels["hud_ready"])
                cost = (monitor.raster_time() - begin) % PAL_FRAME_CYCLES
                require(monitor.memory(labels["hud_dirty"], 1)[0] == 0,
                        "hud_update did not clear hud_dirty")
                wanted = reference.expected_screen(hud_frame,
                                                   game.world.slot, values)
                for name, address, wanted_bytes in (
                        ("HUD bitmap", 0x6000, wanted.bitmap[:3 * 320]),
                        ("HUD screen RAM", 0x4400, wanted.screen[:3 * 40])):
                    require(monitor.memory(address, len(wanted_bytes)) ==
                            bytes(wanted_bytes), f"{name} differs from "
                            f"the reference for {values}")
                return cost
            costs_hud = [show_hud(HUD_TEST), show_hud((8, 0, 0, 0))]
            for number in points:
                monitor.delete_checkpoint(number)
            report["hud"] = {"values_tested": [list(HUD_TEST),
                                               [8, 0, 0, 0]],
                             "hud_update_cycles": max(costs_hud)}

        # --- 5. what the step must show ------------------------------
        events = [e["event"] for e in report["events"]]
        summary = json.loads((reference.GENERATED / "assets.json")
                             .read_text())
        rooms = {r["slot"]: r for r in summary["rooms"]}
        shows = {}

        def show(what, condition, detail=None):
            if args.no_shows:           # a variant: recorded only
                shows[what] = {"ok": bool(condition), "detail": detail}
                return
            require(condition, f"Step {step:02d} must show: {what} "
                               f"({detail})")
            shows[what] = detail if detail is not None else True

        show("frames checked against the model", totals["frames"] >= 256,
             totals["frames"])
        show("the four flame phases", phases == {0, 1, 2, 3},
             sorted(phases))
        if step == S.FIRST_HERO:        # the explorer's own step
            show("all eight walking frames",
                 seen["pointers"] == set(range(8)),
                 sorted(seen["pointers"]))
            show("stopped in all four directions",
                 seen["blocked_dirs"] == {0, 1, 2, 3},
                 sorted(seen["blocked_dirs"]))
            show("stopped by a wall and by a door",
                 {reference.WALL_CELL, reference.DOOR_CELL} <=
                 seen["blocks"], sorted(seen["blocks"]))
            show("horizontal wins over vertical", seen["horizontal"] > 0,
                 seen["horizontal"])
            show("up wins over down", seen["up_wins"] > 0,
                 seen["up_wins"])
        if has["exits"] and not has["objects"]:
            atrio = {s for s, r in rooms.items() if r["zone"] == "atrio"}
            needed = {(s, side) for s in atrio
                      for side, to in rooms[s]["exits"].items()
                      if to in atrio}
            show("every room of the atrio", visited == atrio,
                 sorted(visited))
            show("every opening between them", openings == needed,
                 sorted(openings))
            doors = {s for s, r in rooms.items() if r["door"]}
            show("every door and the portal shut", seen["door_blocks"] ==
                 doors, sorted(seen["door_blocks"]))
        if step == S.FIRST_OBJECTS:     # objects and doors: step 04
            needed = {(s, side) for s, r in rooms.items()
                      for side in r["exits"]}
            show("all sixteen rooms", visited == set(rooms),
                 sorted(visited))
            show("every opening", openings == needed, len(openings))
            won = [e for e in end_states if e["how"] == "won" and
                   e["joystick_only"]]
            show("a game won with the joystick only", bool(won),
                 won and won[0]["frame"])
            won = won[0]
            show("doors A, B, C and the portal opened, keys used, three "
                 "seals", won["doors_open"] == 15 and won["keys"] == 0 and
                 won["seals"] == 3 and won["room"] == start_room,
                 {k: won[k] for k in ("doors_open", "keys", "seals")})
            pages = reference.load("rooms.bin")
            kinds = {}
            for slot in rooms:
                for n in range(2):
                    kind, _, _, number = pages[slot * 256 + 200 + n * 4:
                                               slot * 256 + 204 + n * 4]
                    if kind:
                        kinds[number] = kind
            needed = {n for n, k in kinds.items() if k != W.KIND_POTION}
            show("every key, treasure and seal taken",
                 needed <= set(won["objects_taken"]),
                 sorted(needed - set(won["objects_taken"])))
            show("a potion left on the floor at full energy",
                 seen["potion_refused"] > 0, seen["potion_refused"])
            potions = [e for e in events if e.endswith("(kind 6) taken")]
            show("a potion taken below full energy", bool(potions),
                 len(potions))
            zones = [t["zone"] for t in report["transitions"]]
            show("the four zones", set(zones) == {0, 1, 2, 3},
                 sorted(set(zones)))
            show("the game stands still after its end", seen["still"] > 0,
                 seen["still"])
        if step == S.FIRST_COMBAT:      # the combat: step 05
            pages = reference.load("rooms.bin")
            dungeon = {(s, n) for s in rooms for n in range(C.MAX_ENEMIES)
                       if pages[s * 256 + C.ENEMIES_AT + n * 4]}
            defeated = {(e["room"], int(e["event"].split()[1]))
                        for e in report["events"]
                        if e["event"].startswith("enemy") and
                        e["event"].endswith("defeated")}
            show("every enemy of the dungeon defeated", defeated ==
                 dungeon, sorted(dungeon - defeated))
            show("the blade in four directions", seen["blade"] ==
                 {C.BLADE_FRAME + d for d in range(4)},
                 sorted(seen["blade"]))
            show("every frame of the enemies", seen["enemy_pointers"] ==
                 set(range(C.COMBAT_POINTER, C.DUST_FRAME + 1)),
                 sorted(seen["enemy_pointers"]))
            show("the explorer blinking, an enemy flashing",
                 seen["hidden"] > 0 and seen["flash"] > 0,
                 [seen["hidden"], seen["flash"]])
            show("a hit by the point half way back",
                 totals["near_hits"] > 0, totals["near_hits"])
            show("blows that only hurt", any(e.endswith(" hit")
                                             for e in events))
            lost = [e for e in end_states if e["how"] == "lost"]
            show("GAME OVER with the joystick only",
                 any(e["joystick_only"] for e in lost), len(lost))
            show("energy stopped at zero: a touch with one cell left",
                 seen["clamp"] > 0 and all(e["energy"] == 0 for e in lost),
                 seen["clamp"])
            show("a slow skeleton", "test makes enemy 0 slow" in
                 " ".join(events))
            ends = [(e["how"], e["joystick_only"]) for e in end_states]
            show("won and lost with the joystick only, lost with help",
                 ends == [("won", True), ("lost", True), ("lost", False)],
                 ends)
        if has["sound"]:
            numbers = {labels[f"FX_{name}"]: name for name in
                       ("SLASH", "HIT", "DUST", "PICKUP", "DOOR", "HURT",
                        "LOST", "WON")}
            show("the eight sound effects", set(audio_started) ==
                 set(numbers), sorted(numbers[n] for n in audio_started))
            show("effect priorities", refused > 0 and replaced > 0,
                 [refused, replaced])
            show("theme and both pieces of the end", {labels["SONG_THEME"],
                 labels["SONG_WON"], labels["SONG_LOST"]} <= songs,
                 sorted(songs))
            ends = [(e["how"], e["mode"], e["joystick_only"])
                    for e in end_states]
            show("the ends of the games in every mode", ends == [
                ("won", "FX", True), ("lost", "MUSIC", True),
                ("won", "MUSIC", False), ("lost", "SILENT", True),
                ("lost", "FX", True)], ends)
            show("frames in every mode", all(
                audio_seen["frames"].values()), audio_seen["frames"])
            show("no note left sounding", all(quiet.values()), quiet)
            irq = {kind: {"interrupts": len(v), "cycles_max": max(v),
                          "cycles_mean": round(sum(v) / len(v))}
                   for kind, v in probe["costs"].items() if v}
            show("the sound interrupt timed in every case",
                 set(irq) == set(PROBES) and all(
                     v["cycles_max"] < MUSIC_BUDGET for v in irq.values()),
                 irq)
            report["sound"] = {"frames_by_mode": audio_seen["frames"],
                               "no_stuck_notes": quiet,
                               "interrupt_cycles": irq}
        if costs:
            worst = max(costs)
            report["frame_work"] = {
                "frames_measured": len(costs), "cycles_max": worst[0],
                "worst_game": worst[3], "worst_frame": worst[1],
                "worst_room": worst[2],
                "share_of_frame_max": round(worst[0] / PAL_FRAME_CYCLES, 3),
                "method": "raster position at joy_ready and at the next "
                          "main_loop; frames that draw a room not counted; "
                          "frames counted from each start of the program"}
        draw = [t["draw_cycles"] for t in report["transitions"]]
        if draw:
            report["changes_of_room"] = {
                "count": len(draw), "draw_cycles_min": min(draw),
                "draw_cycles_max": max(draw),
                "openings_used": sorted(f"{s} {side}"
                                        for s, side in openings)}
        report["seen"] = {k: sorted(v) if isinstance(v, set) else v
                          for k, v in seen.items()}
        report["totals"] = {"frames": totals["frames"],
                            "near_hits": totals["near_hits"],
                            "effects_started": {str(k): v for k, v in
                                                audio_started.items()},
                            "refused": refused, "replaced": replaced,
                            "songs": sorted(songs),
                            "frames_by_mode": audio_seen["frames"]}
        report.update(result="PASS", checked_frames=totals["frames"],
                      restarts=restarts, ends_of_games=end_states,
                      total_steps=total_steps,
                      blocked_frames=blocked_frames, shows=shows)
    except Exception as error:
        games = locals().get("restarts")
        if games is not None:           # which game: frames restart
            error = RuntimeError(f"game {games + 1}, {error}")
        report["error"] = str(error)
        raise error
    finally:
        vice.close()
        (evidence / "step-test.json").write_text(
            json.dumps(report, indent=2, default=sorted) + "\n",
            encoding="utf-8", newline="\n")
    print(json.dumps({k: report.get(k) for k in
                      ("result", "step", "data", "starts", "shows",
                       "frame_work", "changes_of_room", "sound", "hud")},
                     indent=2, default=sorted))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--step", type=int, required=True)
    parser.add_argument("--root", type=Path, default=None,
                        help="another copy of the step (mutation tests)")
    parser.add_argument("--evidence", default=None,
                        help="folder of the report, inside the project")
    parser.add_argument("--script", type=Path, default=None,
                        help="another route (a variant's)")
    parser.add_argument("--set", action="append", default=[],
                        help="a Python statement that changes the model "
                             "as a variant changes the program, e.g. "
                             "'combat_model.DAMAGE = 1'")
    parser.add_argument("--no-shows", action="store_true",
                        help="skip what the step's own route must show")
    parser.add_argument("--vice", type=Path, default=DEFAULT_VICE)
    parser.add_argument("--settle", type=float, default=4.0,
                        help="seconds to wait for autostart")
    args = parser.parse_args()
    try:
        verify(args)
    except Exception as error:
        print(f"Step verification FAILED: {error}", file=sys.stderr)
        return 1
    return 0


